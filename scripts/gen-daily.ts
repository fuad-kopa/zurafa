// Generates the daily-puzzle pool: positions from computer self-play where the side to move has exactly one mate
// in one, or exactly one first move that forces mate in two. Run: npm run gen:daily (writes src/puzzles-daily-data.ts).

import { writeFileSync } from 'node:fs';
import { Game } from '../src/engine/game';
import { Searcher } from '../src/ai/search';
import { LEVELS } from '../src/ai/levels';
import { DEFAULT_RULES } from '../src/engine/position';
import { sqName } from '../src/engine/geometry';
import * as P from '../src/engine/pieces';
import { forcedReply, matingMoves } from '../src/puzzles';

interface Gen { men: string[]; side: 0 | 1; swapUsed: [number, number]; goal: 'mate1' | 'mate2' }

const TARGET1 = Number(process.argv[2] ?? 90);
const TARGET2 = Number(process.argv[3] ?? 30);
const OUT_JSON = process.argv[4];
const MINUTES = Number(process.argv[5] ?? 50);
const out: Gen[] = [];
const seen = new Set<string>();
const searcher = new Searcher();

function menOf(g: Game): string[] {
  const b = g.pos.board;
  const men: string[] = [];
  for (let sq = 0; sq < b.length; sq++) if (b[sq]) men.push(`${b[sq] > 0 ? 'w' : 'b'} ${P.TYPE_ID[Math.abs(b[sq])]} ${sqName(sq)}`);
  return men;
}

function mates(g: Game): number[] {
  const res: number[] = [];
  for (const m of [...g.legalMoves()]) {
    g.play(m);
    if (g.result?.reason === 'checkmate' && g.result.winner !== null) res.push(m);
    g.undo();
  }
  return res;
}

/** First moves after which every reply allows a mate (the puzzle module's own test). */
function mate2Keys(g: Game, cap: number): number[] {
  const keys: number[] = [];
  for (const m of [...g.legalMoves()]) {
    g.play(m);
    const ok = !g.result && forcedReply(g) !== null;
    g.undo();
    if (ok) {
      keys.push(m);
      if (keys.length > cap) break;
    }
  }
  return keys;
}

let games = 0;
const t0 = Date.now();
while ((out.filter((x) => x.goal === 'mate1').length < TARGET1 || out.filter((x) => x.goal === 'mate2').length < TARGET2) && Date.now() - t0 < MINUTES * 60_000) {
  games++;
  const g = new Game({ ...DEFAULT_RULES });
  const lv = [LEVELS[1], LEVELS[2]];
  while (!g.result && g.ply < 400) {
    const pos = g.pos;
    if (g.ply >= 30) {
      const key = menOf(g).join('|') + pos.side;
      if (!seen.has(key)) {
        seen.add(key);
        // any immediate win counts (stalemate and a bare king win too), so a mate in one must be the only one
        const m1 = mates(g);
        const wins = matingMoves(g).length;
        if (m1.length === 1 && wins === 1 && out.filter((x) => x.goal === 'mate1').length < TARGET1) {
          out.push({ men: menOf(g), side: pos.side as 0 | 1, swapUsed: [pos.swapUsed[0], pos.swapUsed[1]], goal: 'mate1' });
        } else if (wins === 0 && g.legalMoves().length <= 45 && out.filter((x) => x.goal === 'mate2').length < TARGET2) {
          const k = mate2Keys(g, 1);
          if (k.length === 1) out.push({ men: menOf(g), side: pos.side as 0 | 1, swapUsed: [pos.swapUsed[0], pos.swapUsed[1]], goal: 'mate2' });
        }
      }
    }
    const r = searcher.search(g.pos, lv[g.ply % 2].limits, []);
    g.play(r.move);
  }
  if (games % 5 === 0) console.log(`games ${games}, mate1 ${out.filter((x) => x.goal === 'mate1').length}, mate2 ${out.filter((x) => x.goal === 'mate2').length}, ${Math.round((Date.now() - t0) / 1000)}s`);
}

// a worker of a parallel run only reports its finds; the merge step writes the module
if (OUT_JSON) {
  writeFileSync(OUT_JSON, JSON.stringify(out));
  console.log('json', out.length);
  process.exit(0);
}

// interleave so the daily rotation mixes easy and harder ones
const m1 = out.filter((x) => x.goal === 'mate1');
const m2 = out.filter((x) => x.goal === 'mate2');
const mixed: Gen[] = [];
while (m1.length || m2.length) {
  for (let i = 0; i < 3 && m1.length; i++) mixed.push(m1.shift()!);
  if (m2.length) mixed.push(m2.shift()!);
}
writeFileSync('src/puzzles-daily-data.ts', `// Generated by scripts/gen-daily.ts: positions from computer self-play with a single mate in one or a single
// key move forcing mate in two. Checked again by tests/daily.test.ts.
export const DAILY_DATA: { men: string[]; side: 0 | 1; swapUsed: [number, number]; goal: 'mate1' | 'mate2' }[] = ${JSON.stringify(mixed, null, 0).replace(/\},\{/g, '},\n  {')};
`);
console.log('written', mixed.length);
